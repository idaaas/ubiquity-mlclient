static constexpr char encodingTable[] = "0123456789ABCDEFGHJKMNPQRSTVWXYZ*~$=U";

static inline void encode(
        char *const destination,
        const uint64_t *const source
        ) noexcept
{
    destination[0] = encodingTable[(*source >> 55) & 31];
    destination[1] = encodingTable[(*source >> 50) & 31];
    destination[2] = encodingTable[(*source >> 45) & 31];
    destination[3] = encodingTable[(*source >> 40) & 31];
    destination[4] = encodingTable[(*source >> 35) & 31];
    destination[5] = encodingTable[(*source >> 30) & 31];
    destination[6] = encodingTable[(*source >> 25) & 31];
    destination[7] = encodingTable[(*source >> 20) & 31];
    destination[8] = encodingTable[(*source >> 15) & 31];
    destination[9] = encodingTable[(*source >> 10) & 31];
    destination[10] = encodingTable[(*source >> 5) & 31];
    destination[11] = encodingTable[*source & 31];
    destination[12] = encodingTable[*source % 37];
    destination[13] = 0;
}

