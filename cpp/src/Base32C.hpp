static inline bool decode(
        uint64_t *const destination,
        const char *const source
        ) noexcept
{
    *destination = 0;
#ifndef DISABLE_ID_CHECKS
    if (__glibc_unlikely(strlen(source) != 13)) {
        return 0;
    }
#endif
    *destination |= static_cast<uint64_t>(decodingTable[static_cast<uint8_t>(source[0])]) << 55;
    *destination |= static_cast<uint64_t>(decodingTable[static_cast<uint8_t>(source[1])]) << 50;
    *destination |= static_cast<uint64_t>(decodingTable[static_cast<uint8_t>(source[2])]) << 45;
    *destination |= static_cast<uint64_t>(decodingTable[static_cast<uint8_t>(source[3])]) << 40;
    *destination |= static_cast<uint64_t>(decodingTable[static_cast<uint8_t>(source[4])]) << 35;
    *destination |= static_cast<uint64_t>(decodingTable[static_cast<uint8_t>(source[5])]) << 30;
    *destination |= static_cast<uint64_t>(decodingTable[static_cast<uint8_t>(source[6])]) << 25;
    *destination |= static_cast<uint64_t>(decodingTable[static_cast<uint8_t>(source[7])]) << 20;
    *destination |= static_cast<uint64_t>(decodingTable[static_cast<uint8_t>(source[8])]) << 15;
    *destination |= static_cast<uint64_t>(decodingTable[static_cast<uint8_t>(source[9])]) << 10;
    *destination |= static_cast<uint64_t>(decodingTable[static_cast<uint8_t>(source[10])]) << 5;
    *destination |= static_cast<uint64_t>(decodingTable[static_cast<uint8_t>(source[11])]);
#ifndef DISABLE_ID_CHECKS
    return *destination % 37 == decodingTable[static_cast<uint8_t>(source[12])];
#else
    return true;
#endif
}

